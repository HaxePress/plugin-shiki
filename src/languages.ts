/** Shiki's id for plain text, which needs no grammar. */
export const PLAIN_TEXT = 'text';

/** The grammar for a fence name, or plain text for an unknown or missing one. */
export function grammarName(fence: string): string {
  const name = fence.toLowerCase();
  const resolved = Object.hasOwn(aliases, name) ? aliases[name] : name;
  return Object.hasOwn(grammars, resolved) ? resolved : PLAIN_TEXT;
}
